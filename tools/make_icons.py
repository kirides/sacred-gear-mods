#!/usr/bin/env python3
"""The icon font of the theme: subsets Material Symbols (the file given as the argument) to the icons in tools/icons.txt, writes src/sacred-theme/icons.ttf and the
ICONS block of theme.rcss (@font-face and the classes `icon icon-<name>`; names with '-' for '_'), then regenerates theme-dp.rcss.
Usage: python tools/make_icons.py <path to MaterialSymbolsSharp-Regular.ttf> [--check]. Needs fonttools (pip install fonttools).
The codepoints are read from the font itself (its ligature names are the icon names: GSUB), so any Material Symbols release works."""
import sys, pathlib, subprocess, re
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parent.parent
theme = root / 'src' / 'sacred-theme' / 'theme.rcss'
args = [a for a in sys.argv[1:] if not a.startswith('--')]
if not args:
    sys.exit(__doc__)
src = pathlib.Path(args[0])
names = []
for line in (root / 'tools' / 'icons.txt').read_text(encoding='utf8').splitlines():
    line = line.split('#')[0]
    names += line.split()

font = TTFont(src)
cmap = font.getBestCmap()
rev = {n: c for c, n in cmap.items()}
# icon name -> codepoint through the ligature table (a name is a ligature of its letters)
gsub = font['GSUB'].table
lig = {}
for lookup in gsub.LookupList.Lookup:
    for st in lookup.SubTable:
        st = getattr(st, 'ExtSubTable', st)
        if hasattr(st, 'ligatures'):
            for first, ligs in st.ligatures.items():
                for l in ligs:
                    letters = first + ''.join(l.Component)
                    # glyph names of the letters -> text
                    txt = ''.join(chr(rev[g]) if g in rev else '?' for g in [first] + list(l.Component))
                    lig[txt] = l.LigGlyph
glyph_cp = {}
for c, g in cmap.items():
    glyph_cp.setdefault(g, c)
rows, missing = [], []
for n in names:
    g = lig.get(n)
    cp = glyph_cp.get(g) if g else None
    if cp is None:
        missing.append(n)
    else:
        rows.append((n, cp))
if missing:
    print('not in the font:', ' '.join(missing))
cps = ','.join('U+%04X' % cp for _, cp in rows)
out = root / 'src' / 'sacred-theme' / 'icons.ttf'
if '--check' not in sys.argv:
    subprocess.check_call([sys.executable, '-m', 'fontTools.subset', str(src), '--unicodes=' + cps, '--output-file=' + str(out),
                           '--layout-features=', '--no-hinting', '--name-IDs=*', '--drop-tables+=meta'], stderr=subprocess.DEVNULL)
bs = chr(92)
lines = ['/* ICONS BEGIN (generated by tools/make_icons.py from tools/icons.txt: do not edit) */',
         '@font-face { font-family: "Sacred Icons"; src: url("icons.ttf") format("truetype"); }',
         '.icon { display: inline-block; font-family: "Sacred Icons"; font-weight: normal; font-style: normal; font-size: 1.25em; line-height: 1; vertical-align: -0.2em; }']
for n, cp in sorted(rows):
    lines.append('.icon-%s::before { content: "%s%04x"; }' % (n.replace('_', '-'), bs, cp))
lines.append('/* ICONS END */')
block = '\n'.join(lines)
text = theme.read_text(encoding='utf8')
if '/* ICONS BEGIN' in text:
    new = re.sub(r'/\* ICONS BEGIN.*?/\* ICONS END \*/', lambda m: block, text, flags=re.S)
else:
    new = text.replace('/* SPRITES BEGIN', block + '\n\n/* SPRITES BEGIN', 1)
if '--check' in sys.argv:
    sys.exit(0 if new == text else 1)
theme.write_text(new, encoding='utf8', newline='\n')
subprocess.check_call([sys.executable, str(root / 'tools' / 'make_theme_dp.py')])
print('wrote', len(rows), 'icons,', out.stat().st_size, 'bytes')
