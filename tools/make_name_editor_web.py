#!/usr/bin/env python3
"""Builds docs/name-editor/index.html, the standalone web page of the name editor, from the mod's own files:

  src/name-editor/ui/editor.rml      the part between <!--fragment--> and <!--/fragment--> is the page's content (the same markup the game draws)
  src/name-editor/ui/fragment.rcss   the stylesheet (dp becomes px)
  src/name-editor/data.json          palette, icon ids, presets
  tools/name-editor-web/editor.js    the page's logic (the game's is src/name-editor/main.lua)
  tools/name-editor-web/shim.css     the stand-in for the game's window frame, tab bar and fonts

  python tools/make_name_editor_web.py            writes the page
  python tools/make_name_editor_web.py --check    exits 1 when the page is not up to date (for CI)
The icons come from docs/name-editor/name-icons-atlas.png (placeholders cut from the wiki; the game draws its own UI images), inlined into the page."""
import argparse, base64, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rd(*p):
    with open(os.path.join(ROOT, *p), encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n')


def build():
    rml = rd('src', 'name-editor', 'ui', 'editor.rml')
    m = re.search(r'<!--fragment-->\n(.*?)<!--/fragment-->', rml, re.S)
    if not m:
        sys.exit('no fragment markers in editor.rml')
    fragment = m.group(1).rstrip()
    css = re.sub(r'(\d+(?:\.\d+)?)dp\b', r'\1px', rd('src', 'name-editor', 'ui', 'fragment.rcss'))
    data = json.dumps(json.loads(rd('src', 'name-editor', 'data.json')), ensure_ascii=False, separators=(',', ':'))
    js = rd('tools', 'name-editor-web', 'editor.js')
    with open(os.path.join(ROOT, 'docs', 'name-editor', 'name-icons-atlas.png'), 'rb') as f:
        atlas = base64.b64encode(f.read()).decode('ascii')
    shim = rd('tools', 'name-editor-web', 'shim.css')
    return f'''<!doctype html>
<!-- GENERATED by tools/make_name_editor_web.py from src/name-editor (ui/editor.rml, ui/fragment.rcss, data.json) and tools/name-editor-web: do not edit. -->
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Sacred name editor</title>
<style>
{shim}
{css}</style></head>
<body>
<div class="window"><div class="titlebar">Name editor</div><div class="body">
{fragment}
</div></div>
<p class="hint">Type a name, pick colors and icons, or color it with a gradient; the line under the preview is the raw text Sacred stores (<code>\\cffRRGGBB</code> colors, <code>\\gffffffff00000XXX</code> icons, XXX = hex id of a UI image). Paste a raw name and it is read back. The icons here are placeholders; the Sacred Gear mod <code>name-editor</code> draws the game's own images. Keys: type, arrows, Home/End, Backspace/Delete, Page Up/Down switch the palette; a gamepad: LB/RB palette, B backspace, X copy, Y clear.</p>
<script>window.NAME_EDITOR_DATA = {data};
window.NAME_EDITOR_ATLAS = "data:image/png;base64,{atlas}";</script>
<script>
{js}</script>
</body></html>
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    o = ap.parse_args()
    out = os.path.join(ROOT, 'docs', 'name-editor', 'index.html')
    text = build()
    if o.check:
        cur = open(out, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(out) else ''
        if cur != text:
            print('docs/name-editor/index.html is out of date: run tools/make_name_editor_web.py')
            sys.exit(1)
        return
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', out)


main()
