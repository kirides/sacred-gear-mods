#!/usr/bin/env python3
"""Writes src/sacred-theme/theme-dp.rcss and sprites-dp.rcss from theme.rcss and sprites.rcss: the same stylesheets for documents laid out in screen pixels
(ui.rml.load(path, {dp = true}); see sacred-bild docs/RmlPixelDocuments.md).

In such a document `px` is a screen pixel and `dp` one layout unit, so every length except a hairline (a 1px edge or line) becomes `dp`.
Game pictures (gear:image/N) already scale with the canvas; adding "?dp" scales them a second time. Theme-folder pictures get "?dp" so
their natural size is in layout units.
Run it after every change of theme.rcss or sprites.rcss; `--check` fails when a file is out of date."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'sacred-theme'

def length(m):
    value = float(m.group(1))
    return m.group(0) if value <= 1 else m.group(1) + 'dp'

def convert(name):
    src = (root / (name + '.rcss')).read_text(encoding='utf8').replace('\r\n', '\n')
    out = re.sub(r'(?<![\w.#-])(-?\d*\.?\d+)px\b', lambda m: length(m), src)
    out = re.sub(r'\b((?:bloom-plain|bloom-check|arrow-glow-left|arrow-glow-right)\.png)(?!\?)', r'\1?dp', out)
    header = ('/* GENERATED by tools/make_theme_dp.py from %s.rcss: do not edit. The same stylesheet for documents laid out in screen pixels (dp = true):\n'
              '   lengths in dp (a layout unit), hairlines in px, theme-folder pictures sized in layout units (?dp). */\n' % name)
    return header + out

ok = True
for name in ('theme', 'sprites'):
    if name == 'sprites' and not (root / 'sprites.rcss').exists():
        continue
    text = convert(name)
    target = root / (name + '-dp.rcss')
    if '--check' in sys.argv:
        ok = ok and target.exists() and target.read_text(encoding='utf8') == text
    else:
        target.write_text(text, encoding='utf8', newline='\n')
        print('wrote', target)
if '--check' in sys.argv:
    sys.exit(0 if ok else 1)
