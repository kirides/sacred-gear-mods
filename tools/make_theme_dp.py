#!/usr/bin/env python3
"""Writes src/sacred-theme/theme-dp.rcss from theme.rcss: the same stylesheet for documents laid out in screen pixels
(ui.rml.load(path, {dp = true}); see sacred-bild docs/RmlPixelDocuments.md).

In such a document `px` is a screen pixel and `dp` one layout unit, so every length except a hairline (a 1px edge or line) becomes `dp`.
Game pictures (gear:image/N) already scale with the canvas; adding "?dp" scales them a second time. Theme-folder pictures get "?dp" so
their natural size is in layout units.
Run it after every change of theme.rcss; `--check` fails when the file is out of date."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'sacred-theme'
src = (root / 'theme.rcss').read_text(encoding='utf8')

def length(m):
    value = float(m.group(1))
    return m.group(0) if value <= 1 else m.group(1) + 'dp'

out = re.sub(r'(?<![\w.#-])(-?\d*\.?\d+)px\b', lambda m: length(m), src)
out = re.sub(r'\b((?:bloom-plain|bloom-check|arrow-glow-left|arrow-glow-right)\.png)(?!\?)', r'\1?dp', out)
header = ('/* GENERATED by tools/make_theme_dp.py from theme.rcss: do not edit. The same stylesheet for documents laid out in screen pixels (dp = true):\n'
          '   lengths in dp (a layout unit), hairlines in px, theme-folder pictures sized in layout units (?dp). */\n')
text = header + out
target = root / 'theme-dp.rcss'
if '--check' in sys.argv:
    sys.exit(0 if target.exists() and target.read_text(encoding='utf8') == text else 1)
target.write_text(text, encoding='utf8', newline='\n')
print('wrote', target)
