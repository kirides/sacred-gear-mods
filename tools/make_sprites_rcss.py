#!/usr/bin/env python3
"""Writes the `.sprite-N` classes into src/sacred-theme/theme.rcss (between the SPRITES markers), then run tools/make_theme_dp.py for theme-dp.rcss.

N is the decimal id of a game UI image (the number gear.ui.images() and gear:image/N use). A class gives an element the image at its natural size:
<span class="sprite sprite-218"></span>. The sizes come from tools/sprite-sizes.json, [[id, width, height, sheet], ...], dumped from the game with
gear.ui.images() (the sprite-browser mod shows them all with their numbers).

  python tools/make_sprites_rcss.py            rewrites the block (and theme-dp.rcss)
  python tools/make_sprites_rcss.py --check    exits 1 when theme.rcss is out of date"""
import json, pathlib, re, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
rows = json.loads((root / 'tools' / 'sprite-sizes.json').read_text(encoding='utf8'))
theme = root / 'src' / 'sacred-theme' / 'theme.rcss'
BEGIN = '/* SPRITES BEGIN (generated by tools/make_sprites_rcss.py: do not edit) */'
END = '/* SPRITES END */'
lines = [BEGIN,
         '/* .sprite-N: the game UI image N at its natural size (the sprite-browser mod lists them with their numbers). */',
         '.sprite { display: inline-block; }']
for i, w, h, sheet in sorted(rows):
    lines.append('.sprite-%d { width: %dpx; height: %dpx; decorator: image(gear:image/%d scale-none left top); }' % (i, w, h, i))
lines.append(END)
block = '\n'.join(lines) + '\n'
text = theme.read_text(encoding='utf8').replace('\r\n', '\n')
if BEGIN in text:
    new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n', lambda m: block, text, flags=re.S)
else:
    new = text.rstrip('\n') + '\n\n' + block
if '--check' in sys.argv:
    sys.exit(0 if new == text else 1)
theme.write_text(new, encoding='utf8', newline='\n')
subprocess.check_call([sys.executable, str(root / 'tools' / 'make_theme_dp.py')])
print('wrote', len(rows), 'sprite classes')
