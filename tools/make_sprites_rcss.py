#!/usr/bin/env python3
"""Writes the `.sprite-N` classes into src/sacred-theme/sprites.rcss, then run tools/make_theme_dp.py (or let this do it) for sprites-dp.rcss.

N is the decimal id of a game UI image (the number gear.ui.images() and gear:image/N use). A class gives an element the image at its natural size:
<span class="sprite sprite-218"></span>. The sizes come from tools/sprite-sizes.json, [[id, width, height, sheet], ...], dumped from the game with
gear.ui.images() (the sprite-browser mod shows them all with their numbers).

The classes are not in theme.rcss: they are nine tenths of its rules and RmlUi keeps a copy of every rule per document. mod.lua names the sheet
(`theme_sprites`, `theme_sprites_dp`) and Gear links it only into documents that mention `sprite-` (or load with `sprites = true`).

  python tools/make_sprites_rcss.py            rewrites sprites.rcss (and the -dp files)
  python tools/make_sprites_rcss.py --check    exits 1 when sprites.rcss is out of date"""
import json, pathlib, re, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
rows = json.loads((root / 'tools' / 'sprite-sizes.json').read_text(encoding='utf8'))
folder = root / 'src' / 'sacred-theme'
theme = folder / 'theme.rcss'
sprites = folder / 'sprites.rcss'
lines = ['/* GENERATED by tools/make_sprites_rcss.py from tools/sprite-sizes.json: do not edit.',
         '   .sprite-N: the game UI image N at its natural size (the sprite-browser mod lists them with their numbers). Gear links this sheet into the documents that',
         '   mention a `sprite-` class (mod.lua: theme_sprites); `{sprites = true}` in the load options forces it, `{sprites = false}` leaves it out. */',
         '.sprite { display: inline-block; }']
for i, w, h, sheet in sorted(rows):
    lines.append('.sprite-%d { width: %dpx; height: %dpx; decorator: image(gear:image/%d scale-none left top); }' % (i, w, h, i))
new = '\n'.join(lines) + '\n'
# (older theme.rcss files carried the block between these markers)
old_block = re.compile(r'\n*/\* SPRITES BEGIN .*?/\* SPRITES END \*/\n', re.S)
text = theme.read_text(encoding='utf8').replace('\r\n', '\n')
stripped = old_block.sub('\n', text).rstrip('\n') + '\n'
if '--check' in sys.argv:
    ok = stripped == text and sprites.exists() and sprites.read_text(encoding='utf8') == new
    sys.exit(0 if ok else 1)
if stripped != text:
    theme.write_text(stripped, encoding='utf8', newline='\n')
sprites.write_text(new, encoding='utf8', newline='\n')
subprocess.check_call([sys.executable, str(root / 'tools' / 'make_theme_dp.py')])
print('wrote', len(rows), 'sprite classes')
